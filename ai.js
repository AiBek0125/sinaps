// Преобразование ответа запроса к /api/ask (с поиском по проверенным источникам, таймаутом 10с и 1 ретраем)
export async function askSynapse(
  question,
  {
    subjectName = '',
    useDeepSeek = false,
    useWebSearch = true,
    detailMode = false,
    practiceMode = false,
    previousQuestion = '',
    previousAnswer = '',
    signal = null
  } = {}
) {
  // 1. Сначала клиентская модерация
  const mod = moderateUserInput(question);
  if (!mod.allowed) {
    return {
      ok: true,
      moderated: true,
      answer: mod.reply,
      show: { type: 'none', data: null },
      sources: []
    };
  }

  // 2. Проверка наличия интернета
  if (typeof navigator !== 'undefined' && navigator.onLine === false) {
    return {
      ok: false,
      errorType: 'offline',
      message: 'Нет интернета, но Синапс покажет темы из кэша',
      sources: []
    };
  }

  const doRequest = async () => {
    const controller = new AbortController();
    const onExternalAbort = () => controller.abort();
    if (signal) {
      if (signal.aborted) controller.abort();
      else signal.addEventListener('abort', onExternalAbort, { once: true });
    }
    const timer = setTimeout(() => controller.abort(), 10500);
    try {
      const response = await fetch('/api/ask', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        signal: controller.signal,
        body: JSON.stringify({
          question,
          subject: subjectName,
          useDeepSeek: Boolean(useDeepSeek),
          useWebSearch: Boolean(useWebSearch),
          detailMode: Boolean(detailMode),
          practiceMode: Boolean(practiceMode),
          previousQuestion,
          previousAnswer
        })
      });

      const payload = await response.json().catch(() => ({}));
      const serverSources = Array.isArray(payload?.sources) ? payload.sources : [];

      if (response.status === 401 || payload?.error === 'key_not_configured') {
        return {
          ok: false,
          errorType: 'key_not_configured',
          message: 'Ключ не настроен',
          sources: serverSources,
          fallbackAnswer: payload?.fallbackAnswer || null,
          fallbackShow: payload?.fallbackShow || null
        };
      }

      if (response.status === 503 && payload?.error === 'offline') {
        return {
          ok: false,
          errorType: 'offline',
          message: 'Нет интернета, но Синапс покажет темы из кэша',
          sources: []
        };
      }

      if (!response.ok) {
        const err = new Error(payload?.message || `HTTP ${response.status}`);
        err.status = response.status;
        err.payload = payload;
        throw err;
      }

      if (payload?.blocked) {
        return {
          ok: true,
          blocked: true,
          answer: 'Не могу ответить на этот вопрос',
          show: { type: 'none', data: null },
          sources: []
        };
      }

      const safeShow = isShowDataSafe(payload?.show)
        ? payload?.show || { type: 'none', data: null }
        : { type: 'none', data: null };

      return {
        ok: true,
        provider: payload?.provider || 'gemini',
        answer: String(payload?.answer || '').trim() || 'Уточни у учителя этот вопрос.',
        show: safeShow,
        sources: serverSources
      };
    } finally {
      clearTimeout(timer);
      if (signal) signal.removeEventListener('abort', onExternalAbort);
    }
  };

  const searchQuery =
    (detailMode || practiceMode) && previousQuestion ? previousQuestion : question;

  // Пробуем 1 раз, и при сетевом сбое/таймауте повторяем ещё 1 раз (кроме отмены пользователем)
  let lastError = null;
  for (let attempt = 0; attempt < 2; attempt++) {
    if (signal?.aborted) {
      return { ok: false, errorType: 'aborted', message: 'Остановлено', sources: [] };
    }
    try {
      const result = await doRequest();
      // При 401 или офлайне не повторяем, но при 401 дополняем клиентским поиском из РУВИКИ/Википедии
      if (!result.ok && result.errorType === 'key_not_configured') {
        if (useWebSearch && (!result.sources || result.sources.length === 0)) {
          const clientSources = await searchVerifiedSources(searchQuery, {
            subject: subjectName,
            maxResults: 3
          });
          result.sources = clientSources;
          result.fallbackAnswer = synthesizeAnswerFromSources(searchQuery, clientSources, {
            detailMode,
            practiceMode
          });
          result.fallbackShow = detectTemplateFromQuestion(searchQuery);
        }
        return result;
      }
      if (!result.ok && result.errorType === 'offline') {
        return result;
      }
      return result;
    } catch (err) {
      if (signal?.aborted) {
        return { ok: false, errorType: 'aborted', message: 'Остановлено', sources: [] };
      }
      lastError = err;
    }
  }

  // Если серверлес /api/ask недоступен — делаем прямой поиск по РУВИКИ и Википедии с CORS
  if (useWebSearch && !signal?.aborted) {
    const serverSources = Array.isArray(lastError?.payload?.sources)
      ? lastError.payload.sources
      : [];
    const sources =
      serverSources.length > 0
        ? serverSources
        : await searchVerifiedSources(searchQuery, { subject: subjectName, maxResults: 3 });

    const synthesized =
      lastError?.payload?.fallbackAnswer ||
      synthesizeAnswerFromSources(searchQuery, sources, { detailMode, practiceMode });
    const detectedShow = lastError?.payload?.fallbackShow || detectTemplateFromQuestion(searchQuery);

    if (synthesized) {
      return {
        ok: true,
        provider: 'verified_search',
        answer: synthesized,
        show: isShowDataSafe(detectedShow) ? detectedShow : { type: 'none', data: null },
        sources
      };
    }
  }

  return {
    ok: false,
    errorType: 'network_error',
    message:
      lastError?.name === 'AbortError'
        ? 'Время ожидания истекло. Попробуй задать вопрос текстом или выбери тему.'
        : 'Не удалось связаться с ИИ-сервером. Проверь соединение или открой «5 тем предмета».',
    sources: []
  };
}
